from chip8.system.config import (
    MEMORY_SIZE,
    FONT_CHIP8_START,
    PROGRAM_START,
)

FONTSET = [
    0xF0,0x90,0x90,0x90,0xF0,
    0x20,0x60,0x20,0x20,0x70,
    0xF0,0x10,0xF0,0x80,0xF0,
    0xF0,0x10,0xF0,0x10,0xF0,
    0x90,0x90,0xF0,0x10,0x10,
    0xF0,0x80,0xF0,0x10,0xF0,
    0xF0,0x80,0xF0,0x90,0xF0,
    0xF0,0x10,0x20,0x40,0x40,
    0xF0,0x90,0xF0,0x90,0xF0,
    0xF0,0x90,0xF0,0x10,0xF0,
    0xF0,0x90,0xF0,0x90,0x90,
    0xE0,0x90,0xE0,0x90,0xE0,
    0xF0,0x80,0x80,0x80,0xF0,
    0xE0,0x90,0x90,0x90,0xE0,
    0xF0,0x80,0xF0,0x80,0xF0,
    0xF0,0x80,0xF0,0x80,0x80,
]


class Memory:
    """
    Mémoire principale du CHIP-8 (4KB)
    """

    def __init__(self):
        self.ram = bytearray(MEMORY_SIZE)
        self._load_fontset()

    def _load_fontset(self) -> None:
        for i, byte in enumerate(FONTSET):
            self.ram[FONT_CHIP8_START + i] = byte

    def reset(self) -> None:
        self.ram = bytearray(MEMORY_SIZE)
        self._load_fontset()

    def load_rom(self, data: bytes) -> None:
        if len(data) + PROGRAM_START > MEMORY_SIZE:
            raise MemoryError("ROM too large for available memory")

        self.ram[PROGRAM_START:PROGRAM_START + len(data)] = data
